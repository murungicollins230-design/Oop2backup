    private void BSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BSaveActionPerformed
String s1 = txtName.getText();
String s2 = txtPassword.getText();
String s3 = txtConfirm.getText();
        
        if (s1.isEmpty()|| s2.isEmpty()||s3.isEmpty()){
            JOptionPane.showMessageDialog(this,"please enter all fields frist");
            return;
        }
        if (!s2.trim().equals(s3.trim())){
            JOptionPane.showMessageDialog(this,"Please enter the same Password!");
            return;
        }
            

        String query ="INSERT INTO login_info(Name,Password)VALUES(?,?)";
        try{
            PreparedStatement statement = con.prepareStatement(query);
            statement.setString(1, s1);
            statement.setString(2, s2);
            
            statement.executeUpdate();

            
            JOptionPane.showMessageDialog(this,"Saved Successfully");
Menu.Main();
this.dispose();

           
            
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this,"Error saving student:"+e.getMessage());
        }
   
          
    }//GEN-LAST:event_BSaveActionPerformed

