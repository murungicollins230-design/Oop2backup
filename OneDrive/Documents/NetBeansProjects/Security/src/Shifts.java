    private java.sql.Time parseTime(String t){
        t = t.trim().toUpperCase().replace("","");
    
        try{
            java.time.LocalTime it =java.time.LocalTime.parse(t,
                java.time.format.DateTimeFormatter.ofPattern("h:mma"));
                return java.sql.Time.valueOf(it);
        }catch(Exception e1){
            try{
                return java.sql.Time.valueOf(t);
            }catch(Exception e){
                return null;
            }
            
        }
    }
    
