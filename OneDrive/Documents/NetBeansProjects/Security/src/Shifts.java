    private void savebActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savebActionPerformed
        try{
            if(ID.getText().trim().isEmpty()||Start.getText().trim().isEmpty()||
                End.getText().trim().isEmpty()){
                JOptionPane.showMessageDialog(this,"Fill All fields");
                return;
            }
            if(Name.getSelectedItem()==null|| Status.getSelectedItem()==null){
                JOptionPane.showMessageDialog(this,"Combobox is empty");
                return;
            }

            String query ="INSERT INTO shifts(shift_id,shift_name,start_time,end_time,required_guards,status,site_id)"
                    + "VALUES(?,?,?,?,?,?,?)";

            PreparedStatement ps = con.prepareStatement(query);

            ps.setInt(1, Integer.parseInt(ID.getText()));
            ps.setString(2, Name.getSelectedItem().toString());
            ps.setTime(3, parseTime(Start.getText()));
            ps.setTime(4, parseTime(End.getText()));
            ps.setString(5, Number.getValue().toString());
            ps.setString(6,Status.getSelectedItem().toString());
            ps.setInt(7, Integer.parseInt(cmbSite.getSelectedItem().toString()));

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Saved");
            loadShifts();
            clearFields();

        }catch(SQLException e){
            JOptionPane.showMessageDialog(this,"Error saving :"+e.getMessage());
        }
    }//GEN-LAST:event_savebActionPerformed
