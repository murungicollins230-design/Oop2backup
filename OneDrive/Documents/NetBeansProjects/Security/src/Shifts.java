    private void loadShifts(){
        try{
            if(rs!=null){
                rs.close();
            }
            if(st!=null){
                st.close();
            }
            st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE,ResultSet.CONCUR_READ_ONLY);
            rs = st.executeQuery("Select*FROM shifts");
            
            if(rs.next()){
                displayResults();
            }
            else{
                System.out.println("EMpty!");
            }
            
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void displayResults(){
        try{
        ID.setText(String.valueOf(rs.getString("shift_id")));
        Start.setText(rs.getString("start_time"));
        End.setText(rs.getString("end_time"));
        Name.setSelectedItem(rs.getString("shift_name"));
        Number.setValue(rs.getInt("required_guards"));
        Status.setSelectedItem(rs.getString("status"));
        cmbSite.setSelectedItem(String.valueOf(rs.getString("site_id")));
        } catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void loadSite(){
        try{
           
            st= con.createStatement();
            rs=st.executeQuery("Select site_id from security_sites");
            cmbSite.removeAllItems();
            while(rs.next()){
                cmbSite.addItem(String.valueOf(rs.getString("site_id")));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
        
    }

