    private void loadContracts(){
        try{
            
            if(st!=null){
                st.close();
            }
            if(rs!=null){
                rs.close();
            }
            st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE,ResultSet.CONCUR_READ_ONLY);
            String query = "SELECT*FROM contracts";
            rs=st.executeQuery(query);
            
            if(rs.next()){
                displayContracts();
            }
            else{
                ID.setText("");
            }
           
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void loadClients(){
        try{
            rs=st.executeQuery("SELECT client_id FROM clients");
            cmbClient.removeAllItems();
            while(rs.next()){
                cmbClient.addItem(rs.getString("client_id"));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void loadSites(){
        try{
            rs=st.executeQuery("SELECT site_id FROM security_sites");
            cmbSite.removeAllItems();
            while(rs.next()){
                cmbSite.addItem(rs.getString("site_id"));
                
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void displayContracts(){
        try{
        ID.setText(String.valueOf(rs.getString("contract_id")));
        java.sql.Date sqlDate=rs.getDate("start_date");
        if(sqlDate != null){
            Start.setDate(sqlDate.toLocalDate());
        }
        java.sql.Date sqlDate2=rs.getDate("end_date");
        if(sqlDate2 != null){
            Stop.setDate(sqlDate2.toLocalDate());
        }
        Service.setSelectedItem(rs.getString("service_type"));
        Monthly.setText(rs.getString("monthly_fee"));
        Status.setSelectedItem(rs.getString("status"));
        spnGuards.setValue(rs.getInt("number_of_guards"));
        cmbClient.setSelectedItem(rs.getString("client_id"));
        cmbSite.setSelectedItem(rs.getString("site_id"));
        
    }catch(SQLException e){
        System.out.println("Error:"+e.getMessage());
    }
    }

