    private void loadPatrol(){
        try{
            if(rs!=null){
                rs.close();
            }
            if(st!=null){
                st.close();
            }
            st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE,ResultSet.CONCUR_READ_ONLY);
            rs = st.executeQuery("Select*FROM patrols");
            
            if(rs.next()){
                displayResults();
            }
            else{
                System.out.println("EMpty!");
            }
            
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void displayResults(){
        try{
        ID.setText(String.valueOf(rs.getString("patrol_id")));
        java.sql.Date sqlDate=rs.getDate("patrol_date");
        if(sqlDate != null){
            Date.setDate(sqlDate.toLocalDate());
        }
        Start.setText(rs.getString("start_time"));
        End.setText(rs.getString("end_time"));
        Area.setSelectedItem(rs.getString("area_covered"));
        Observation.setText(rs.getString("observations"));
        Status.setSelectedItem(rs.getString("status"));
        Guard.setSelectedItem(String.valueOf(rs.getString("idGUARDS")));
        Site.setSelectedItem(String.valueOf(rs.getString("site_id")));
        } catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void loadGuards(){
        try{
           
            st= con.createStatement();
            rs=st.executeQuery("Select idGUARDS from guards");
            Guard.removeAllItems();
            while(rs.next()){
                Guard.addItem(String.valueOf(rs.getString("idGUARDS")));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
        
    }
    private void loadSite(){
        try{
           
            st= con.createStatement();
            rs=st.executeQuery("Select site_id from security_sites");
            Site.removeAllItems();
            while(rs.next()){
                Site.addItem(String.valueOf(rs.getString("site_id")));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
        
    }

