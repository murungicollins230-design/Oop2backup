    private void savebActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savebActionPerformed
        try{
            if(ID.getText().trim().isEmpty()||Location.getText().trim().isEmpty()||
                Name.getText().trim().isEmpty()||
                Person.getText().trim().isEmpty()){
                JOptionPane.showMessageDialog(this,"Fill All fields");
                return;
            }
            if(Type.getSelectedItem()==null|| Status.getSelectedItem()==null){
                JOptionPane.showMessageDialog(this,"Combobox is empty");
                return;
            }

            String query ="INSERT INTO security_sites(site_id,site_name,location,"
                    + "site_type,Contact_person,Status,client_id)VALUES(?,?,?,?,?,?,?)";

            PreparedStatement ps = con.prepareStatement(query);

            ps.setInt(1, Integer.parseInt(ID.getText()));
            ps.setString(2, Name.getText());
            ps.setString(3, Location.getText());
            ps.setString(4,Type.getSelectedItem().toString());
            ps.setString(5, Person.getText());
            ps.setString(6,Status.getSelectedItem().toString());
            ps.setInt(7, Integer.parseInt(Client.getSelectedItem().toString()));

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Saved");
            loadSites();
            clearFields();

        }catch(SQLException e){
            JOptionPane.showMessageDialog(this,"Error saving :"+e.getMessage());
        }
    }//GEN-LAST:event_savebActionPerformed
