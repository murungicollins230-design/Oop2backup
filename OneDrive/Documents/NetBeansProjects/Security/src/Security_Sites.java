    private void loadSites(){
        try{
            if(rs!=null){
                rs.close();
            }
            if(st!=null){
                st.close();
            }
            st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE,ResultSet.CONCUR_READ_ONLY);
            rs = st.executeQuery("Select*FROM security_sites");
            
            if(rs.next()){
                displayResults();
            }
            else{
                System.out.println("EMpty!");
            }
            
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
     private void displayResults(){
        try{
        ID.setText(String.valueOf(rs.getString("site_id")));
        Name.setText(rs.getString("site_name"));
        Location.setText(rs.getString("location"));
        Type.setSelectedItem(rs.getString("site_type"));
        Person.setText(rs.getString("Contact_person"));
        Status.setSelectedItem(rs.getString("Status"));
        Client.setSelectedItem(String.valueOf(rs.getString("client_id")));
        } catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
     private void loadClient(){
        try{
           
            st= con.createStatement();
            rs=st.executeQuery("Select client_id from clients");
            Client.removeAllItems();
            while(rs.next()){
                Client.addItem(String.valueOf(rs.getString("client_id")));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
        
    }

