    private void loadAttendance(){
        try{
            
            if(st!=null){
                st.close();
            }
            if(rs!=null){
                rs.close();
            }
            st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE,ResultSet.CONCUR_READ_ONLY);
            String query = "SELECT*FROM attendance";
            rs=st.executeQuery(query);
            
            if(rs.next()){
                displayAttendance();
            }
            else{
                txtAttend.setText("");
            }
           
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    
    private void loadGuards(){
        try{
           
            st= con.createStatement();
            rs=st.executeQuery("Select idGUARDS from guards");
            cmbGuardID.removeAllItems();
            while(rs.next()){
                cmbGuardID.addItem(String.valueOf(rs.getString("idGUARDS")));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
        
    }
    private void loadShifts(){
        try{
            Statement s1 = con.createStatement();
            ResultSet s2 = s1.executeQuery("Select shift_id FROM shifts");
            cmbShiftID.removeAllItems();
            while (s2.next()){
                cmbShiftID.addItem(String.valueOf(s2.getString("shift_id")));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
            }
        }
    private void displayAttendance(){
        try{
        txtAttend.setText(String.valueOf(rs.getString("attendance_id")));
        java.sql.Date sqlDate=rs.getDate("attendance_date");
        if(sqlDate != null){
            DAttend.setDate(sqlDate.toLocalDate());
        }
        TIN.setText(rs.getString("check_in"));
        TOut.setText(rs.getString("check_out"));
        Status.setSelectedItem(rs.getString("status"));
        cmbGuardID.setSelectedItem(String.valueOf(rs.getString("idGUARDS")));
        cmbShiftID.setSelectedItem(String.valueOf(rs.getString("shift_id")));
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }

