    private void loadDocument(){
        try{
            if(rs!=null){
                rs.close();
            }
            if(st!=null){
                st.close();
            }
            st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE,ResultSet.CONCUR_READ_ONLY);
            rs = st.executeQuery("Select*FROM guard_documents");
            
            if(rs.next()){
                displayResults();
            }
            else{
                System.out.println("EMpty!");
            }
            
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void loadGuards(){
        try{
           
            st= con.createStatement();
            rs=st.executeQuery("Select idGUARDS from guards");
            cmbGuard.removeAllItems();
            while(rs.next()){
                cmbGuard.addItem(String.valueOf(rs.getString("idGUARDS")));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
        
    }
    private void displayResults(){
        try{
        ID.setText(String.valueOf(String.valueOf(rs.getString("document_id"))));
        java.sql.Date sqlDate=rs.getDate("Issue_Date");
        if(sqlDate != null){
            Start.setDate(sqlDate.toLocalDate());
        }
        java.sql.Date sqlDate1=rs.getDate("Expiry_Date");
        if(sqlDate1 != null){
            Stop.setDate(sqlDate1.toLocalDate());
        }
        NO.setText(rs.getString("Document_number"));
        Position.setSelectedItem(rs.getString("Document_type"));
        Status.setSelectedItem(rs.getString("Status"));
        cmbGuard.setSelectedItem(String.valueOf(rs.getString("GUARDS_id")));
        } catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }

