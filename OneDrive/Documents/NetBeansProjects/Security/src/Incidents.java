    private void savebActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savebActionPerformed
        try{
            if(ID.getText().trim().isEmpty()||Description.getText().trim().isEmpty()||
                    Action.getText().trim().isEmpty()||Incident.getDate()==null||
                By.getText().trim().isEmpty()){
                JOptionPane.showMessageDialog(this,"Fill All fields");
                return;
            }
            if(Type.getSelectedItem()==null|| Status.getSelectedItem()==null||
                Seve.getSelectedItem()==null){
                JOptionPane.showMessageDialog(this,"Combobox is empty");
                return;
            }

            String query ="INSERT INTO incidents(incident_id,incedent_type,incident_date,description,"
            + "action_taken,severity,status,reported_by,site_id,idGUARDS,idUSERS)VALUES(?,?,?,?,?,?,?,?,?,?,?)";

            PreparedStatement ps = con.prepareStatement(query);

            ps.setInt(1, Integer.parseInt(ID.getText()));
            ps.setString(2,Type.getSelectedItem().toString());
            java.time.LocalDate id =Incident.getDate();
            ps.setDate(3, java.sql.Date.valueOf(id));
            ps.setString(4, Description.getText());
            ps.setString(5, Action.getText());
            ps.setString(6,Seve.getSelectedItem().toString());
            ps.setString(7,Status.getSelectedItem().toString());
            ps.setString(8, By.getText());
            ps.setInt(9, Integer.parseInt(Site.getSelectedItem().toString()));
            ps.setInt(10, Integer.parseInt(Guard.getSelectedItem().toString()));
            ps.setInt(11, Integer.parseInt(User.getSelectedItem().toString()));

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Saved");
            loadIncidents();
            clearFields();

        }catch(SQLException e){
            JOptionPane.showMessageDialog(this,"Error saving :"+e.getMessage());
        }
    }//GEN-LAST:event_savebActionPerformed
    private void clearFields(){
        ID.setText("");
        By.setText("");
        Action.setText("");
        Incident.clear();
        Description.setText("");
        Status.setSelectedIndex(0);
        Type.setSelectedIndex(0);
        Seve.setSelectedIndex(0);
    }
    private void deletebActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deletebActionPerformed
        String id = ID.getText().trim();
        if(id.isEmpty()){
            JOptionPane.showMessageDialog(this,"Not found");
            return;
        }
        int d =Integer.parseInt(id);

        String query = "DELETE FROM incidents WHERE incident_id =?";
        try{
            PreparedStatement statement  = con.prepareStatement(query);
            statement.setInt(1, d);
            int result = statement.executeUpdate();
            if(result>0){
                JOptionPane.showMessageDialog(this,"Deleted successfully");

            }else{
                JOptionPane.showMessageDialog(this,"Not found");
            }

            clearFields();
            loadIncidents();
        }catch (SQLException e){
            JOptionPane.showMessageDialog(this,"Error deleting "+e.getMessage());
        }
    }//GEN-LAST:event_deletebActionPerformed

