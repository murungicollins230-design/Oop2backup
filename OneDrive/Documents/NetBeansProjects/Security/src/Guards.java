    private void savebActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savebActionPerformed
        try{
            if(ID.getText().trim().isEmpty()||NO.getText().trim().isEmpty()||
                    First.getText().trim().isEmpty()||Address.getText().trim().isEmpty()||
                    Phone.getText().trim().isEmpty()||
                    Last.getText().trim().isEmpty()||
                    Hire.getDate()==null||DOB.getDate()==null){
                JOptionPane.showMessageDialog(this,"Fill All fields");
                return;
            }
            if(Rank.getSelectedItem()==null|| Status.getSelectedItem()==null||
                Gender.getSelectedItem()==null){
                JOptionPane.showMessageDialog(this,"Combobox is empty");
                return;
            }

            String query ="INSERT INTO guards(idGUARDS,employee_no,First_name,Last_name,"
            + "Gender,DOB,Phone,Address,Hire_date,`Rank`,`Status`)VALUES(?,?,?,?,?,?,?,?,?,?,?)";

            PreparedStatement ps = con.prepareStatement(query);

            ps.setInt(1, Integer.parseInt(ID.getText()));
            ps.setString(2, NO.getText());
            ps.setString(3, First.getText());
            ps.setString(4, Last.getText());
            ps.setString(5, Gender.getSelectedItem().toString());
            java.time.LocalDate id =DOB.getDate();
            ps.setDate(6, java.sql.Date.valueOf(id));
            ps.setString(7, Phone.getText().toString());
            ps.setString(8, Address.getText());
            java.time.LocalDate id1 =Hire.getDate();
            ps.setDate(9, java.sql.Date.valueOf(id1));
            ps.setString(10, Rank.getSelectedItem().toString());
            ps.setString(11,Status.getSelectedItem().toString());

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Saved");
            loadGuards();
            clearFields();

        }catch(SQLException e){
            JOptionPane.showMessageDialog(this,"Error saving :"+e.getMessage());
        }
    }//GEN-LAST:event_savebActionPerformed
    private void clearFields(){
        ID.setText("");
        NO.setText("");
        First.setText("");
        Last.setText("");
        Phone.setText("");
        Address.setText("");
        DOB.clear();
        Hire.clear();
        Status.setSelectedIndex(0);
        Gender.setSelectedIndex(0);
        Rank.setSelectedIndex(0);
    }
    private void deletebActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deletebActionPerformed
        String id = ID.getText().trim();
        if(id.isEmpty()){
            JOptionPane.showMessageDialog(this,"Not found");
            return;
        }
        int d =Integer.parseInt(id);

        String query = "DELETE FROM guards WHERE idGUARDS =?";
        try{
            PreparedStatement statement  = con.prepareStatement(query);
            statement.setInt(1, d);
            int result = statement.executeUpdate();
            if(result>0){
                JOptionPane.showMessageDialog(this,"Deleted successfully");

            }else{
                JOptionPane.showMessageDialog(this,"Not found");
            }

            clearFields();
            loadGuards();
        }catch (SQLException e){
            JOptionPane.showMessageDialog(this,"Error deleting "+e.getMessage());
        }
    }//GEN-LAST:event_deletebActionPerformed

