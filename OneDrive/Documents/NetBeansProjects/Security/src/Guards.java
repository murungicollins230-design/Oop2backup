    private void loadGuards(){
        try{
            if(rs!=null){
                rs.close();
            }
            if(st!=null){
                st.close();
            }
            st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE,ResultSet.CONCUR_READ_ONLY);
            rs = st.executeQuery("Select*FROM guards");
            
            if(rs.next()){
                displayResults();
            }
            else{
                System.out.println("EMpty!");
            }
            
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void displayResults(){
        try{
        ID.setText(String.valueOf(rs.getString("idGUARDS")));
        NO.setText(rs.getString("employee_no"));
        First.setText(rs.getString("First_name"));
        Last.setText(rs.getString("Last_name"));
        Gender.setSelectedItem(rs.getString("Gender"));
        java.sql.Date sqlDate=rs.getDate("DOB");
        if(sqlDate != null){
            DOB.setDate(sqlDate.toLocalDate());
        }
        Phone.setText(rs.getString("Phone"));
        Address.setText(rs.getString("Address"));
        java.sql.Date sqlDate1=rs.getDate("Hire_date");
        if(sqlDate1 != null){
            Hire.setDate(sqlDate1.toLocalDate());
        }
        Rank.setSelectedItem(rs.getString("Rank"));
        Status.setSelectedItem(rs.getString("Status"));
        
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }

