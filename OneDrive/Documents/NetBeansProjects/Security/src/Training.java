    private void savebActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savebActionPerformed
        try{
            if(ID.getText().trim().isEmpty()||Provider.getText().trim().isEmpty()||
                Date.getText().trim().isEmpty()||date.getText().trim().isEmpty()){
                JOptionPane.showMessageDialog(this,"Fill All fields");
                return;
            }
            if(Name.getSelectedItem()==null|| Status.getSelectedItem()==null||
                Level.getSelectedItem()==null){
                JOptionPane.showMessageDialog(this,"Combobox is empty");
                return;
            }

            String query ="INSERT INTO training(training_id,training_name,provider,start_date,end_date,TRAININGcol,"
                    + "status,idGUARDS)VALUES(?,?,?,?,?,?,?,?)";

            PreparedStatement ps = con.prepareStatement(query);

            ps.setInt(1, Integer.parseInt(ID.getText()));
            ps.setString(2, Name.getSelectedItem().toString());
            ps.setString(3, Provider.getText());
            java.time.LocalDate id =Date.getDate();
            ps.setDate(4, java.sql.Date.valueOf(id));
            java.time.LocalDate id1 =date.getDate();
            ps.setDate(5, java.sql.Date.valueOf(id));
            ps.setString(6, Level.getSelectedItem().toString());
            ps.setString(7,Status.getSelectedItem().toString());
            ps.setInt(8, Integer.parseInt(Guard.getSelectedItem().toString()));

            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Saved");
            loadTraining();
            clearFields();

        }catch(SQLException e){
            JOptionPane.showMessageDialog(this,"Error saving :"+e.getMessage());
        }
    }//GEN-LAST:event_savebActionPerformed
