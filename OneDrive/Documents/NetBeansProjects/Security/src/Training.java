    private void loadTraining(){
        try{
            if(rs!=null){
                rs.close();
            }
            if(st!=null){
                st.close();
            }
            st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE,ResultSet.CONCUR_READ_ONLY);
            rs = st.executeQuery("Select*FROM training");
            
            if(rs.next()){
                displayResults();
            }
            else{
                System.out.println("EMpty!");
            }
            
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void displayResults(){
        try{
        ID.setText(String.valueOf(rs.getString("training_id")));
        java.sql.Date sqlDate=rs.getDate("start_date");
        if(sqlDate != null){
            Date.setDate(sqlDate.toLocalDate());
        }
        java.sql.Date sqlDate1=rs.getDate("end_date");
        if(sqlDate1 != null){
            date.setDate(sqlDate1.toLocalDate());
        }
        Provider.setText(rs.getString("provider"));
        Name.setSelectedItem(rs.getString("training_name"));
        Level.setSelectedItem(rs.getString("TRAININGcol"));
        Status.setSelectedItem(rs.getString("status"));
        Guard.setSelectedItem(String.valueOf(rs.getString("idGUARDS")));
        } catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void loadGuards(){
        try{
           
            st= con.createStatement();
            rs=st.executeQuery("Select idGUARDS from guards");
            Guard.removeAllItems();
            while(rs.next()){
                Guard.addItem(String.valueOf(rs.getString("idGUARDS")));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
        
    }
