    private void loadUsers(){
        try{
            if(rs!=null){
                rs.close();
            }
            if(st!=null){
                st.close();
            }
            st = con.createStatement(ResultSet.TYPE_SCROLL_INSENSITIVE,ResultSet.CONCUR_READ_ONLY);
            rs = st.executeQuery("Select*FROM users");
            
            if(rs.next()){
                displayResults();
            }
            else{
                System.out.println("EMpty!");
            }
            
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void displayResults(){
        try{
        ID.setText(String.valueOf(rs.getString("idUSERS")));
        Name.setText(rs.getString("username"));
        Password.setText(rs.getString("password"));
        email.setText(rs.getString("email"));
        Phone.setText(rs.getString("phone"));
        Status.setSelectedItem(rs.getString("status"));
        Roles.setSelectedItem(String.valueOf(rs.getString("ROLES_id")));
        } catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
    }
    private void loadRoles(){
        try{
           
            st= con.createStatement();
            rs=st.executeQuery("Select idROLES from roles");
            Roles.removeAllItems();
            while(rs.next()){
                Roles.addItem(String.valueOf(rs.getString("idROLES")));
            }
        }catch(SQLException e){
            System.out.println("Error:"+e.getMessage());
        }
        
    }
